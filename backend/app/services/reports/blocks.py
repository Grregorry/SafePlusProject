def draw_page_header_footer(
    canvas: Any,
    document: SimpleDocTemplate,
) -> None:
    canvas.saveState()

    canvas.setStrokeColor(SLATE_200)
    canvas.setLineWidth(0.5)
    canvas.line(
        document.leftMargin,
        PAGE_HEIGHT - 24 * mm,
        PAGE_WIDTH - document.rightMargin,
        PAGE_HEIGHT - 24 * mm,
    )

    canvas.setFont("Helvetica-Bold", 8)
    canvas.setFillColor(DARK_CYAN)
    canvas.drawString(
        document.leftMargin,
        PAGE_HEIGHT - 19 * mm,
        getattr(
            document,
            "report_name",
            "SafePlus Assessment Report",
        ),
    )

    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(SLATE_500)
    canvas.drawRightString(
        PAGE_WIDTH - document.rightMargin,
        PAGE_HEIGHT - 19 * mm,
        "Confidential assessment information",
    )

    canvas.setStrokeColor(SLATE_200)
    canvas.line(
        document.leftMargin,
        18 * mm,
        PAGE_WIDTH - document.rightMargin,
        18 * mm,
    )

    canvas.setFont("Helvetica", 7.5)
    canvas.setFillColor(SLATE_500)
    canvas.drawString(
        document.leftMargin,
        12 * mm,
        "Generated by SafePlus",
    )

    canvas.drawRightString(
        PAGE_WIDTH - document.rightMargin,
        12 * mm,
        f"Page {document.page}",
    )

    canvas.restoreState()


def summary_card(
    label: str,
    value: str,
    styles: dict[str, ParagraphStyle],
    background: colors.Color = SLATE_100,
    value_colour: colors.Color = SLATE_900,
) -> Table:
    table = Table(
        [
            [
                Paragraph(
                    html_text(label),
                    styles["small"],
                )
            ],
            [
                Paragraph(
                    f"<b>{html_text(value)}</b>",
                    ParagraphStyle(
                        "CardValue",
                        parent=styles["body"],
                        fontName="Helvetica-Bold",
                        fontSize=18,
                        leading=21,
                        textColor=value_colour,
                        spaceAfter=0,
                    ),
                )
            ],
        ],
        colWidths=[49 * mm],
        rowHeights=[8 * mm, 14 * mm],
    )

    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), background),
                ("BOX", (0, 0), (-1, -1), 0.5, SLATE_200),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ]
        )
    )

    return table


def overall_result_card(
    assessment: Assessment,
    styles: dict[str, ParagraphStyle],
) -> Table:
    """The overall result with its maturity ladder, as on the results
    page: the level is named in text next to the score."""

    score = assessment.overall_combined_mean
    level = (
        assessment.overall_maturity_label
        or maturity_level(score)
    )

    value_style = ParagraphStyle(
        "OverallValue",
        parent=styles["body"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=DARK_CYAN,
        spaceAfter=0,
    )

    card = Table(
        [
            [
                [
                    Paragraph(
                        "Overall result",
                        styles["small"],
                    ),
                    Paragraph(
                        html_text(level),
                        value_style,
                    ),
                    Paragraph(
                        f"<b>{score_text(score)}</b> out of 5",
                        styles["body"],
                    ),
                ],
                maturity_ladder(
                    "Overall score",
                    score,
                    width=290,
                ),
            ]
        ],
        colWidths=[56 * mm, 116 * mm],
    )

    card.setStyle(
        TableStyle(
            [
                ("BOX", (0, 0), (-1, -1), 0.5, SLATE_200),
                ("LEFTPADDING", (0, 0), (-1, -1), 10),
                ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                ("TOPPADDING", (0, 0), (-1, -1), 9),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 9),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ]
        )
    )

    return card


def domain_card(
    domain_name: str,
    combined_mean: Decimal | None,
    question_count: int,
    lowest_lines: list[str],
    styles: dict[str, ParagraphStyle],
    width: float = 172 * mm,
) -> Table:
    """One domain: its ladder, how many questions were scored, and the
    lowest scoring question in that domain."""

    cell: list[Any] = [
        maturity_ladder(
            domain_name,
            combined_mean,
            width=width - 20,
        ),
        Spacer(1, 1 * mm),
        Paragraph(
            (
                f"{question_count} scored "
                f"{'question' if question_count == 1 else 'questions'}"
            ),
            styles["small"],
        ),
    ]

    for line in lowest_lines:
        cell.append(
            Paragraph(
                (
                    f'<font color="{LOWEST.hexval()}">'
                    f"<b>{html_text(line)}</b></font>"
                ),
                styles["small"],
            )
        )

    card = Table([[cell]], colWidths=[width])

    card.setStyle(
        TableStyle(
            [
                ("BOX", (0, 0), (-1, -1), 0.5, SLATE_200),
                ("LEFTPADDING", (0, 0), (-1, -1), 10),
                ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                ("TOPPADDING", (0, 0), (-1, -1), 8),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]
        )
    )

    return card


def bullet_items(
    values: list[object],
    styles: dict[str, ParagraphStyle],
) -> list[Paragraph]:
    return [
        Paragraph(
            f"&#8226; {html_text(value)}",
            styles["body"],
        )
        for value in values
        if value not in (None, "")
    ]


class ReportDocTemplate(SimpleDocTemplate):
    """Records the page each tagged heading lands on, so the contents
    page can be filled in on the second pass."""

    def afterFlowable(self, flowable: Any) -> None:
        entry = getattr(flowable, "toc_entry", None)

        if entry is None:
            return

        level, text = entry

        self.notify(
            "TOCEntry",
            (level, text, self.page),
        )


def tag_contents_entry(
    flowable: Any,
    text: str,
    level: int = 0,
) -> Any:
    """Marks a flowable so it appears in the contents."""

    flowable.toc_entry = (level, text)

    return flowable


def contents_block(
    styles: dict[str, ParagraphStyle],
    own_page: bool,
) -> list[Any]:
    """The contents list. Long reports get their own page; short ones
    keep it on the first page."""

    contents = TableOfContents()
    contents.levelStyles = [
        ParagraphStyle(
            "ContentsLevel0",
            parent=styles["body"],
            fontName="Helvetica-Bold",
            fontSize=10,
            leading=16,
            textColor=SLATE_900,
            spaceAfter=0,
        ),
        ParagraphStyle(
            "ContentsLevel1",
            parent=styles["body"],
            fontName="Helvetica",
            fontSize=9,
            leading=14,
            textColor=SLATE_600,
            leftIndent=10,
            spaceAfter=0,
        ),
    ]
    contents.dotsMinLevel = 0

    block: list[Any] = []

    if own_page:
        block.append(PageBreak())

    block.extend(
        [
            Paragraph("Contents", styles["section"]),
            contents,
        ]
    )

    block.append(
        PageBreak() if own_page else Spacer(1, 7 * mm)
    )

    return block


def source_titles(
    source_ids: object,
    guidance_sources: list[object],
) -> list[str]:
    """Turn the AI's source ids into the titles shown on screen."""

    titles: dict[str, str] = {}

    for source_item in guidance_sources:
        source = as_dict(source_item)
        source_id = str(source.get("source_id", ""))

        if source_id:
            titles[source_id] = str(
                source.get("title", source_id)
            )

    return [
        titles.get(str(value), str(value))
        for value in as_list(source_ids)
        if value
    ]


def section_heading(
    text: str,
    styles: dict[str, ParagraphStyle],
) -> Paragraph:
    heading = Paragraph(
        html_text(text),
        styles["section"],
    )

    return tag_contents_entry(heading, text)


def ai_section_header(
    analysis: AIAnalysis | None,
    styles: dict[str, ParagraphStyle],
    width: float = 172 * mm,
) -> Any:
    """The AI analysis banner from the results page: AI content is kept
    visually distinct, and says which model wrote it and when.

    A report downloaded as Review only carries no AI content, so it
    gets a plain heading instead of the banner."""

    if analysis is None or analysis.status != "completed":
        return section_heading("AI analysis", styles)

    left: list[Any] = [
        Paragraph(
            f'<font color="{VIOLET_700.hexval()}"><b>AI ANALYSIS</b></font>',
            styles["small"],
        ),
        Paragraph(
            "WorkSafe-grounded improvement analysis",
            styles["subsection"],
        ),
        Paragraph(
            (
                "Recommendations use the assessment evidence together "
                "with curated official WorkSafe SafePlus guidance. "
                "Nothing in this section changes the calculated results."
            ),
            styles["body"],
        ),
    ]

    right: list[Any] = [
        Paragraph(
            f"<b>{html_text(analysis.ai_provider)}</b>",
            styles["small"],
        ),
        Paragraph(
            f"Generated {date_text(analysis.generated_at)}",
            styles["small"],
        ),
    ]

    header = Table(
        [[left, right]],
        colWidths=[width * 0.62, width * 0.38],
    )

    header.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), VIOLET_50),
                ("BOX", (0, 0), (-1, -1), 0.9, VIOLET_300),
                ("LEFTPADDING", (0, 0), (-1, -1), 10),
                ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                ("TOPPADDING", (0, 0), (-1, -1), 9),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 9),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]
        )
    )

    return tag_contents_entry(header, "AI analysis")


def domain_cards(
    domain_rows: list[tuple[str, Decimal, str]],
    question_rows: list[Any],
    domain_index: int,
    number_index: int,
    combined_index: int,
    gap_index: int,
    lowest_mean: Decimal | None,
    styles: dict[str, ParagraphStyle],
    width: float = 172 * mm,
) -> list[Any]:
    """A ladder per domain, with its question count and lowest
    scoring question."""

    flowables: list[Any] = []

    for domain_name, domain_mean, _maturity in domain_rows:
        rows_for_domain = [
            row
            for row in question_rows
            if str(row[domain_index]) == domain_name
        ]

        lowest_lines = [
            (
                f"Question {row[number_index]} is the lowest scoring "
                f"question ({score_text(row[combined_index])})"
            )
            for row in rows_for_domain
            if lowest_mean is not None
            and row[combined_index] is not None
            and not is_hidden(row[gap_index])
            and Decimal(str(row[combined_index])) == lowest_mean
        ]

        flowables.extend(
            [
                domain_card(
                    domain_name,
                    domain_mean,
                    len(rows_for_domain),
                    lowest_lines,
                    styles,
                    width=width,
                ),
                Spacer(1, 4 * mm),
            ]
        )

    return flowables
